export function translate(text, language = 'en', values = {}) {
  if (typeof text !== 'string') return text;
  const hasOwn = (object, key) => Object.prototype.hasOwnProperty.call(object, key);
  const translated = language === 'es' && hasOwn(spanishTranslations, text)
    ? spanishTranslations[text]
    : text;
  return translated.replace(/\{(\w+)\}/g, (placeholder, key) => hasOwn(values, key) ? String(values[key]) : placeholder);
}
